"""Regenerate guarded font deltas from original atlas DDS files and glyph metrics.
Requires Pillow; inputs: FONT.dds, FONT-metrics.bin, FONT-mip1/2/3.dds.
Example: python scripts/generate_hungarian_font_data.py --assets build/font-review
"""
import argparse
import math
import struct
from pathlib import Path
from PIL import Image

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--assets',type=Path,required=True)
parser.add_argument('--out',type=Path,default=Path(__file__).resolve().parents[1]/'CoD3Host/hungarian_font_data.h')
args=parser.parse_args()
root=args.assets.resolve()

def tiled_offset(x,y,pitch=128):
    macro=((x>>5)+(y>>5)*(pitch>>5))<<11
    micro=((x&7)+((y&14)<<2))<<4
    off=macro+((micro&~15)<<1)+(micro&15)+((y&1)<<4)
    return ((off&~511)<<3)+((y&16)<<7)+((off&448)<<2)+(((((y&8)>>2)+(x>>3))&3)<<6)+(off&63)

def visible(pixel): return pixel[0]*pixel[3]//255
def accent_end(im):
    active=False
    for y in range(im.height):
        bright=max(visible(im.getpixel((x,y))) for x in range(im.width))
        if bright>32: active=True
        elif active and bright<8: return y
    raise ValueError('accent is not separated from the letter')

def encode_block(pixels):
    a0=max(p[3] for p in pixels);a1=min(p[3] for p in pixels)
    ap=[a0,a1]+[(a0*(7-i)+a1*i)//7 for i in range(1,7)]
    ai=sum(min(range(8),key=lambda j:abs(ap[j]-p[3]))<<(3*i) for i,p in enumerate(pixels))
    # These are monochrome font atlases: preserve their white/black endpoints.
    c0=0xffff;c1=0
    cp=[(255,)*3,(0,)*3,(170,)*3,(85,)*3]
    ci=sum(min(range(4),key=lambda j:sum((cp[j][c]-p[c])**2 for c in range(3)))<<(2*i) for i,p in enumerate(pixels))
    return bytes((a0,a1))+ai.to_bytes(6,'little')+struct.pack('<HHI',c0,c1,ci)

out=['// Generated by scripts/generate_hungarian_font_data.py; do not edit blocks by hand.',
     '// Hungarian double acute glyph deltas for the title\'s own three fonts.',
     '// BC3 blocks in the original Xenos tiled/endian layout; original bytes guard each patch.',
     '// Glyph bodies and accents come from the corresponding original font.',
     '#pragma once', '#include <cstdint>', 'namespace HungarianFontData {',
     'struct Block { uint32_t offset; uint8_t before[16], after[16]; };']
for font in ['garamond','i_helvetica_bold','i_helvetica_bold_italic']:
    original=Image.open(root/(font+'.dds')).convert('RGBA')
    atlas=original.copy();mb=(root/(font+'-metrics.bin')).read_bytes()
    metrics=lambda ch:struct.unpack_from('>7i',mb,(ord(ch)-32)*28)
    changes={}
    rectangles=[]
    for code,grave,acute,umlaut in zip('ÕõÛû','ÒòÙù','ÓóÚú','ÖöÜü'):
        gm=metrics(grave);am=metrics(acute);um=metrics(umlaut)
        crop=lambda m:original.crop((m[0],m[1],m[0]+m[2],m[1]+m[3]))
        src=crop(am);dots=crop(um)
        end=accent_end(src);dot_end=accent_end(dots)
        active=[x for x in range(dots.width) if max(visible(dots.getpixel((x,y))) for y in range(dot_end))>96]
        groups=[]
        for x in active:
            if not groups or x>groups[-1][-1]+1: groups.append([x])
            else:groups[-1].append(x)
        assert len(groups)==2,(font,umlaut,groups)
        centers=[(g[0]+g[-1])/2+um[4]-gm[4] for g in groups]
        xs=[x for x in range(src.width) if max(visible(src.getpixel((x,y))) for y in range(end))>32]
        center=(min(xs)+max(xs))/2
        glyph=Image.new('RGBA',(gm[2],gm[3]),(255,255,255,0))
        body=src.copy()
        for y in range(end):
            for x in range(src.width):body.putpixel((x,y),(255,255,255,0))
        glyph.alpha_composite(body,(am[4]-gm[4],am[5]-gm[5]))
        accent=src.crop((min(xs),0,max(xs)+1,end))
        # A double acute needs two separate strokes. A single acute is too
        # wide in the serif font and would overlap its neighbour.
        width=min(accent.width,max(2,math.floor(centers[1]-centers[0])-2))
        accent=accent.resize((width,end),Image.Resampling.LANCZOS)
        center=(width-1)/2
        for c in centers:
            shift=round(c-center)
            glyph.alpha_composite(accent,(shift,am[5]-gm[5]))
        atlas.paste(glyph,(gm[0],gm[1]))
        rectangles.append((gm[0],gm[1],gm[0]+gm[2],gm[1]+gm[3]))
        changes[ord(code)]=gm
        print(font,code,'storage',grave,'accent centers',centers,'split',end)
    atlas.save(root/(font+'-hu-atlas.png'))
    blocks=(root/(font+'.dds')).read_bytes()[128:]
    patches=[]
    for by in range(64):
        for bx in range(128):
            box=(bx*4,by*4,bx*4+4,by*4+4)
            a=original.crop(box);b=atlas.crop(box)
            if a.tobytes()==b.tobytes():continue
            before=blocks[(by*128+bx)*16:(by*128+bx+1)*16]
            after=encode_block(list(b.getdata()))
            swap=lambda block:bytes(v for j in range(0,16,2) for v in (block[j+1],block[j]))
            patches.append((tiled_offset(bx,by),swap(before),swap(after)))
    out.append(f'inline constexpr Block {font}[] = {{')
    for off,b,a in patches:
        f=lambda arr:'{'+','.join(f'0x{x:02X}' for x in arr)+'}'
        out.append(f'    {{0x{off:X}, {f(b)}, {f(a)}}},')
    out.append('};')
    print(font,len(patches),'blocks')
    # Match the renderer's three smaller, separately tiled mip levels too.
    mip_patches=[]
    for level,pitch,base_offset in [(1,64,0),(2,32,32768),(3,32,49152)]:
        scale=1<<level
        original_mip=Image.open(root/(font+f'-mip{level}.dds')).convert('RGBA')
        new_mip=original_mip.copy()
        reduced=atlas.resize(original_mip.size,Image.Resampling.BOX)
        for x0,y0,x1,y1 in rectangles:
            rect=(x0//scale,y0//scale,math.ceil(x1/scale),math.ceil(y1/scale))
            new_mip.paste(reduced.crop(rect),rect)
        mip_blocks=(root/(font+f'-mip{level}.dds')).read_bytes()[128:]
        for by in range(original_mip.height//4):
            for bx in range(original_mip.width//4):
                box=(bx*4,by*4,bx*4+4,by*4+4)
                a=original_mip.crop(box);b=new_mip.crop(box)
                if a.tobytes()==b.tobytes():continue
                index=(by*(original_mip.width//4)+bx)*16
                before=mip_blocks[index:index+16]
                after=encode_block(list(b.getdata()))
                mip_patches.append((base_offset+tiled_offset(bx,by,pitch),swap(before),swap(after)))
    out.append(f'inline constexpr Block {font}_mips[] = {{')
    for off,b,a in mip_patches:
        out.append(f'    {{0x{off:X}, {f(b)}, {f(a)}}},')
    out.append('};')
    print(font,len(mip_patches),'mip blocks')
    # Render exactly the glyphs the game will use, with its own metrics.
    sample='árvíztűrő tükörfúrógép'
    canvas=Image.new('RGBA',(650,90),(20,20,18,255));x=22
    for c in sample:
        code={'ő':0xf5,'ű':0xfb}.get(c,ord(c))
        m=changes.get(code) or metrics(chr(code))
        if c!=' ':canvas.alpha_composite(atlas.crop((m[0],m[1],m[0]+m[2],m[1]+m[3])),(x+m[4],26+m[5]))
        x+=m[6]
    canvas.crop((0,0,x+22,90)).resize(((x+22)*3,270)).save(root/(font+'-hu-sample.png'))
out.append('}')
args.out.write_text('\n'.join(out)+'\n',encoding='utf-8')
